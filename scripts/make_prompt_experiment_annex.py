"""Writes report/appendices/prompt_experiments.tex from data/evaluation/prompt_experiments/*.json and the
recorded grounded_answer comparison (agent_results_hybrid.json, agent_results_prompt_v3.json).

usage: python scripts/make_prompt_experiment_annex.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EV = ROOT / "data" / "evaluation"
OUT = ROOT / "report" / "appendices" / "prompt_experiments.tex"


def load(p):
    return json.loads((EV / p).read_text(encoding="utf-8"))


def f3(x):
    return f"{x:.3f}"


def main() -> None:
    it = load("prompt_experiments/intent_router_results.json")["summary"]
    dl_doc = load("prompt_experiments/dialogue_understanding_results.json")
    dl, dv = dl_doc["summary"], dl_doc["summary_after_production_validation"]
    tr = load("prompt_experiments/translate_items_results.json")["summary"]
    a = load("agent_results_hybrid.json")["prompt_comparison"]
    b = load("agent_results_prompt_v3.json")["prompt_comparison"]
    rows = [
        r"\code{grounded\_answer} v1$\rightarrow$v2 (historical) & 12 dev questions, same passages & accepted "
        + f"{f3(a['v1']['accepted']['rate'])}$\\rightarrow${f3(a['v2']['accepted']['rate'])}; language "
        + f"{f3(a['v1']['language_ok']['rate'])}$\\rightarrow${f3(a['v2']['language_ok']['rate'])}; evidence span "
        + f"{f3(a['v1']['evidence_found']['rate'])}$\\rightarrow${f3(a['v2']['evidence_found']['rate'])} (trade-off); "
        + f"v3: evidence {f3(b['v3']['evidence_found']['rate'])}, median {b['v3']['median_seconds']:.1f}\\,s vs {b['v2']['median_seconds']:.1f}\\,s, not adopted \\\\",
        r"\code{intent\_router} B0$^\dagger\rightarrow$v1 & 84 dev questions, LLM path only & category "
        + f"{f3(it['B0']['all']['category_accuracy'])}$\\rightarrow${f3(it['v1']['all']['category_accuracy'])}; both labels "
        + f"{f3(it['B0']['all']['both_correct'])}$\\rightarrow${f3(it['v1']['all']['both_correct'])}; Derja intent "
        + f"{f3(it['B0']['derja']['intent_accuracy'])}$\\rightarrow${f3(it['v1']['derja']['intent_accuracy'])} (not improved); valid enums "
        + f"{f3(it['B0']['all']['enum_valid'])}$\\rightarrow${f3(it['v1']['all']['enum_valid'])} \\\\",
        r"\code{dialogue\_understanding} v1$\rightarrow$v2$\rightarrow$v3 (historical) & 18 synthetic declarations & schema-valid "
        + f"{dl['v1']['schema_valid']}/{dl['v2']['schema_valid']}/{dl['v3']['schema_valid']} of 18; invented application/residence "
        + f"{dv['v1']['raw_wrong_application_or_residence']}/{dv['v2']['raw_wrong_application_or_residence']}/{dv['v3']['raw_wrong_application_or_residence']}; "
        + f"after code validation precision {f3(dv['v1']['after_validation_item_precision'])}/{f3(dv['v2']['after_validation_item_precision'])}/{f3(dv['v3']['after_validation_item_precision'])}, "
        + f"recall {f3(dv['v1']['after_validation_item_recall'])}/{f3(dv['v2']['after_validation_item_recall'])}/{f3(dv['v3']['after_validation_item_recall'])} \\\\",
        r"\code{translate\_items} B0$^\dagger\rightarrow$v1 & 11 official FR checklist scenarios & accepted by the production validator "
        + f"{tr['B0']['accepted_by_production_validator']}/11$\\rightarrow${tr['v1']['accepted_by_production_validator']}/11 "
        + r"(B0 rewrote ``14/05/1975'' as ``May 14, 1975'' and dropped ``3/4 cm'') \\",
    ]
    tex = [
        "% Generated by scripts/make_prompt_experiment_annex.py -- do not edit by hand.",
        r"\section{Prompt before/after experiments}\label{app:prompt_experiments}",
        r"Identical inputs, same model and decoding options (local Ollama 0.40.4, temperature~0), sequential calls through the",
        r"project's own client. $^\dagger$B0 is a \emph{controlled baseline} written on 18 October 2026 for prompts that have a",
        r"single stored version: same output format, techniques removed (role, language/script notice, definitions, constraints).",
        r"It is not a historical prompt. Raw outputs: \code{data/evaluation/prompt\_experiments/}; reproduce with",
        r"\code{scripts/prompt\_experiments.py}.",
        r"\begin{center}\footnotesize",
        r"\begin{tabularx}{\textwidth}{@{}p{4.0cm} p{2.8cm} X@{}}",
        r"\toprule Prompt (before$\rightarrow$after) & Test & Measured result \\ \midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabularx}",
        r"\end{center}",
        "",
    ]
    OUT.write_text("\n".join(tex), encoding="utf-8")
    print("written", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
