"""Checklist Builder agent.

Builds the answer from the *official structure* of the retrieved documents, deterministically:
the retrieved passages identify the document and scenario (e.g. "passport renewal, resident
abroad"), and the complete sections (conditions, required documents, place, deadline) are then
read verbatim from the extracted official text. No item is ever generated by a model.

The LLM is used for one optional step only: translating the verbatim items when the user's
language differs from the source language. The translation is validated (same number of lines,
same numbers) and rejected otherwise, in which case the original text is shown.
"""

import logging
import re

from agents import i18n
from agents.corpus import Corpus, Scenario, Section, norm
from agents.llm import LLMError, OllamaChatClient
from agents.prompts import PromptLibrary
from agents.schemas import ChecklistResult, ChecklistSection, ComposeRequest, RouteDecision
from rag.retrieval import Citation, RetrievedPassage

log = logging.getLogger(__name__)

FEE_LINE = re.compile(r"\d+\s*(?:dinars?|دينارا?|دنانير|TND|DT)\b|timbre|redevance|طابع|معلوم", re.I)
AMOUNT = re.compile(r"(\d+(?:[.,]\d+)?)\s*(?:dinars?|دينارا?|دنانير|TND|DT)", re.I)
NUMBER = re.compile(r"\d+(?:[.,/]\d+)*")

SECTION_ORDER = {
    "required_documents": ["documents", "conditions", "place", "delay"],
    "fees": ["fees", "documents"],
    "processing_time": ["delay", "place"],
    "submission_place": ["place", "delay"],
    "eligibility": ["conditions"],
    "procedure_info": ["conditions", "documents", "place", "delay"],
}
HINT_PATTERNS = {
    "abroad": re.compile(r"étranger|etranger|بالخارج", re.I),
    "loss": re.compile(r"perte|vol\b|duplicata|ضياع|السرقة|نظير", re.I),
    "renewal": re.compile(r"renouvellement|تجديد", re.I),
    "modification": re.compile(r"changement|modification|تغيير", re.I),
    "first_time": re.compile(r"première fois|أول مرة|لأوّل مرّة", re.I),
    "pilgrimage": re.compile(r"p[èé]lerinage|الحج", re.I),
}
TARGET_LANGUAGE = {"en": "en", "fr": "fr", "ar": "ar", "derja": "ar"}  # Derja users read MSA sources
# Machine translation is only applied towards these languages. FR->AR output of the local
# translation model was evaluated on the official national ID guide and produced meaning-changing
# errors that passed format validation (e.g. "veuve" -> "العوراء"), so Arabic and Derja users
# get the verbatim official text instead.
TRANSLATION_TARGETS = {"en"}
SOURCE_LANGUAGE_NAMES = {"fr": "French", "ar": "Arabic", "en": "English"}
ICONS = {"passport": "🛂", "national_id": "🪪", "business_registration": "🏢"}
MAX_ROWS = 3
RNE_TABLE_DOC = "rne-formalities-procedure-table"
RNE_TOP_PASSAGES = 5
RNE_CODE_QUERY = re.compile(r"\bRNE\s*([CIM]\s*\d{3}(?:\.\d+)*)", re.I)
RNE_EXTRACTS = 2  # how many of the top passages may be quoted when they are not table rows
RNE_EXTRACT_CHARS = 700


class ChecklistBuilder:
    def __init__(self, corpus: Corpus, llm: OllamaChatClient | None, prompts: PromptLibrary, gate=None, verifier=None):
        self.corpus = corpus
        self.llm = llm
        self.prompts = prompts
        self.gate = gate  # agents.answerability.AnswerabilityGate (optional)
        self.verifier = verifier  # agents.verification.EvidenceVerifier (optional)

    # ------------------------------------------------------------------ entry point
    def build(self, req: ComposeRequest) -> ChecklistResult:
        route = req.route
        if route.context is not None:
            from agents.dialogue import personalize
            # Preserve existing evidence gates and official extraction; personalize only their result.
            base_route = route.model_copy(update={"context": None, "intent": "required_documents" if route.intent == "remaining_documents" else route.intent})
            base_req = req.model_copy(update={"query": route.retrieval_query or req.query, "route": base_route})
            result = self.build(base_req)
            # Business rows have their own labelled rendering, not guide section kinds.
            if route.procedure_category == "business_registration":
                return result
            if result.found and route.intent == "remaining_documents":
                return personalize(result,route.context,route.language)
            if result.found:
                focus_kind = {"fees":"fees", "processing_time":"delay", "submission_place":"place", "eligibility":"conditions"}.get(route.intent)
                if focus_kind:
                    result.sections = [section for section in result.sections if section.kind == focus_kind]
                    self._attach_fee_warning(result, route.intent)
                result.alternatives = []
                result.text = self._render(route,(result.translation or {}).get("title", result.scenario or ""),result)
            return result
        if self.gate is not None and req.passages and not self.gate.assess(req.query, route, req.passages).answerable:
            # The procedure was only guessed (LLM fallback) and the evidence does not support it.
            return ChecklistResult(text=i18n.t("insufficient_evidence", route.language), found=False)
        if self.verifier is not None and req.passages and not self.verifier.check_topic(req.query, route, req.passages).consistent:
            return ChecklistResult(text=i18n.t("topic_mismatch", route.language), found=False)
        if route.procedure_category == "business_registration":
            return self._business(req)
        return self._procedure_guide(req)

    # ------------------------------------------------------------------ procedure guides
    def _procedure_guide(self, req: ComposeRequest) -> ChecklistResult:
        route, lang = req.route, req.route.language
        candidates = self._scenario_candidates(req.passages)
        # Never choose a special loss/change/pilgrimage scenario the user did not state.
        candidates = [(doc, sc) for doc,sc in candidates if all(
            hint in route.hints or (hint == "modification" and "loss" in route.hints
                                   and HINT_PATTERNS["loss"].search(" ".join(sc.path)))
            or not HINT_PATTERNS[hint].search(" ".join(sc.path))
            for hint in ("loss","modification","pilgrimage")
        )]
        if not candidates:
            return ChecklistResult(text=i18n.t("not_found", lang), found=False)
        doc_id, scenario = self._choose(candidates, route)

        # Prefer the parallel official version written in the user's language, if aligned.
        target = TARGET_LANGUAGE[lang]
        doc_lang = self._doc_language(doc_id)
        parallel = self._parallel(doc_id, scenario)
        fee_discrepancy = None
        if parallel and doc_lang != target and parallel[2] == target:
            (doc_id, scenario), parallel = (parallel[0], parallel[1]), (doc_id, scenario, doc_lang)
            doc_lang = target
        if parallel:
            fee_discrepancy = self._fee_discrepancy(lang, (doc_id, scenario, doc_lang), parallel)

        sections = self._select_sections(scenario, route.intent)
        if not sections:
            return ChecklistResult(text=i18n.t("not_found", lang), found=False)
        citations = [c for c in [self.corpus.citation(doc_id, scenario.path, scenario.page)] if c]
        if parallel:
            c = self.corpus.citation(parallel[0], parallel[1].path, parallel[1].page)
            if c:
                citations.append(c)

        title = scenario.title
        translation = None
        if doc_lang in SOURCE_LANGUAGE_NAMES and doc_lang != target:
            title, translation = self._translate(scenario.title, sections, doc_lang, target, doc_id)

        alternatives = [s.title for s in self.corpus.scenarios(doc_id) if s.index != scenario.index]
        if translation and translation.get("method") == "explicit_cin_ar_v1" and translation.get("validated"):
            from agents.checklist_arabic import translate_cin
            alternatives = translate_cin(alternatives) or []
        result = ChecklistResult(
            text="", found=True, doc_id=doc_id, scenario=scenario.title, source_language=doc_lang,
            sections=sections, alternatives=alternatives, citations=citations,
            translation=translation, fee_discrepancy=fee_discrepancy,
        )
        self._attach_fee_warning(result, route.intent)
        result.text = self._render(route, title, result)
        return result

    @staticmethod
    def _attach_fee_warning(result: ChecklistResult, intent: str) -> None:
        """A conflict between official versions on fee amounts matters when the answer shows an amount or the user
        asked about fees; it is not shown with an unrelated answer such as the submission place."""
        if not result.fee_discrepancy:
            return
        shown = [i for s in result.sections for i in (s.items + (s.translated_items or []))]
        relevant = intent == "fees" or any(AMOUNT.search(i) for i in shown)
        result.warnings = [w for w in result.warnings if w != result.fee_discrepancy]
        if relevant:
            result.warnings.append(result.fee_discrepancy)

    def _scenario_candidates(self, passages: list[RetrievedPassage]) -> list[tuple[str, Scenario]]:
        out: list[tuple[str, Scenario]] = []
        for p in passages:
            if p.citation.document_type not in (None, "procedure_guide"):
                continue
            scenarios = self.corpus.scenarios(p.citation.doc_id)
            path = {norm(h) for h in p.citation.heading_path}
            for sc in scenarios:
                if (p.citation.doc_id, sc.index) not in {(d, s.index) for d, s in out}:
                    out.append((p.citation.doc_id, sc))
        return out

    @staticmethod
    def _choose(candidates: list[tuple[str, Scenario]], route: RouteDecision) -> tuple[str, Scenario]:
        def hint_score(sc: Scenario) -> int:
            title = " ".join(sc.path)
            score = sum(1 for h in route.hints if h in HINT_PATTERNS and HINT_PATTERNS[h].search(title))
            if "abroad" not in route.hints and HINT_PATTERNS["abroad"].search(title):
                score -= 1  # default to residents in Tunisia unless the user mentions living abroad
            if "loss" not in route.hints and HINT_PATTERNS["loss"].search(title):
                score -= 1
            if "pilgrimage" not in route.hints and HINT_PATTERNS["pilgrimage"].search(title):
                score -= 1  # special-purpose travel document, only when asked for
            if "modification" not in route.hints and "loss" not in route.hints and HINT_PATTERNS["modification"].search(title):
                score -= 1  # e.g. a generic fee question should not land on "change of passport"
            return score

        # Stable sort keeps the retrieval order among equally matching scenarios.
        return sorted(candidates, key=lambda c: hint_score(c[1]), reverse=True)[0]

    def _doc_language(self, doc_id: str) -> str:
        rec = self.corpus.records().get(doc_id)
        return rec.language.value if rec else "unknown"

    def _parallel(self, doc_id: str, scenario: Scenario) -> tuple[str, Scenario, str] | None:
        """Same procedure guide published in another language, with an identical structure."""
        records = self.corpus.records()
        rec = records.get(doc_id)
        if rec is None:
            return None
        mine = self.corpus.scenarios(doc_id)
        shape = [[s.kind for s in sc.sections] for sc in mine]
        for other in records.values():
            if (other.doc_id == doc_id or other.procedure_category != rec.procedure_category
                    or other.document_type != rec.document_type or other.language == rec.language):
                continue
            theirs = self.corpus.scenarios(other.doc_id)
            if [[s.kind for s in sc.sections] for sc in theirs] == shape:
                return other.doc_id, theirs[scenario.index], other.language.value
        return None

    @staticmethod
    def _fee_discrepancy(lang: str, a: tuple[str, Scenario, str], b: tuple[str, Scenario, str]) -> str | None:
        def amounts(sc: Scenario) -> list[str]:
            return sorted({m.group(1) for s in sc.sections if s.kind == "documents" for i in s.items
                           for m in AMOUNT.finditer(i)}, key=float)

        va, vb = amounts(a[1]), amounts(b[1])
        if va and vb and va != vb:
            label = i18n.SOURCE_LANGUAGE_LABEL
            return i18n.t("discrepancy", lang, lang_a=label.get(a[2], a[2]), lang_b=label.get(b[2], b[2]),
                          values_a="/".join(va), values_b="/".join(vb))
        return None

    @staticmethod
    def _select_sections(scenario: Scenario, intent: str) -> list[ChecklistSection]:
        by_kind: dict[str, list[Section]] = {}
        for s in scenario.sections:
            by_kind.setdefault(s.kind, []).append(s)
        out: list[ChecklistSection] = []
        for kind in SECTION_ORDER.get(intent, SECTION_ORDER["procedure_info"]):
            if kind == "fees":
                items = [i for s in by_kind.get("documents", []) for i in s.items if FEE_LINE.search(i)]
                if items:
                    out.append(ChecklistSection(kind="fees", heading=by_kind["documents"][0].heading, items=items))
                continue
            for s in by_kind.get(kind, []):
                if s.items:
                    out.append(ChecklistSection(kind=kind, heading=s.heading, items=list(s.items)))
        return out

    # ------------------------------------------------------------------ translation
    def _translate(self, title: str, sections: list[ChecklistSection], source: str, target: str, doc_id: str | None = None):
        if target == "ar":
            # The local model's FR->AR output previously changed legal meaning. Use a bounded
            # application translation only for exact passages of the indexed CIN guide.
            from agents.checklist_arabic import translate_cin
            lines = [title] + [item for section in sections for item in section.items]
            translated = translate_cin(lines) if source == "fr" and doc_id == "interior-national-id-guide-fr" else None
            if translated is None or not all(_same_numbers(a, b) for a, b in zip(lines, translated)):
                return title, {"validated": False, "reason": "translation_unavailable"}
            position = 1
            for section in sections:
                section.translated_items = translated[position:position + len(section.items)]
                position += len(section.items)
            return translated[0], {"validated": True, "method": "explicit_cin_ar_v1", "seconds": 0.0, "title": translated[0]}
        if target not in TRANSLATION_TARGETS:
            return title, {"validated": False, "reason": "translation_unavailable"}
        if self.llm is None:
            return title, {"validated": False, "reason": "llm_disabled"}
        lines = [title] + [i for s in sections for i in s.items]
        spec = self.prompts.get("translate_items")
        numbered = "\n".join(f"{n}. {line.replace(chr(10), ' ')}" for n, line in enumerate(lines, 1))
        try:
            res = self.llm.run(spec, items=numbered, source_language_name=SOURCE_LANGUAGE_NAMES[source],
                               target_language_name=SOURCE_LANGUAGE_NAMES[target])
        except LLMError as exc:
            log.warning("translation_failed", extra={"fields": {"error": type(exc).__name__}})
            return title, {"validated": False, "reason": "llm_error", "prompt_ref": spec.ref}
        translated = _parse_numbered(res.text, len(lines))
        info = {"model": res.model, "prompt_ref": res.prompt_ref, "seconds": res.seconds}
        if translated is None or not all(_same_numbers(a, b) for a, b in zip(lines, translated)):
            return title, {**info, "validated": False, "reason": "validation_failed"}
        pos = 1
        for s in sections:
            s.translated_items = translated[pos : pos + len(s.items)]
            pos += len(s.items)
        return translated[0], {**info, "validated": True}

    # ------------------------------------------------------------------ business registration (RNE)
    def _business(self, req: ComposeRequest) -> ChecklistResult:
        lang, route = req.route.language, req.route
        # A requested procedure code that is not in the official table must not be answered with other rows.
        asked = RNE_CODE_QUERY.search(req.query)
        asked_codes = list(dict.fromkeys(re.sub(r"\s+", "", m).upper() for m in RNE_CODE_QUERY.findall(req.query)))
        if asked:
            compact = re.sub(r"\s+", "", asked.group(1)).upper()
            code = f"RNE {compact[0]} {compact[1:]}"
            table = [b["text"] for b in self.corpus.blocks(RNE_TABLE_DOC) if b["kind"] == "table_row"]
            wanted = re.sub(r"\s+", "", code).upper()
            if not any(re.sub(r"\s+", "", row.splitlines()[0].split(":", 1)[-1]).upper() == wanted for row in table):
                c = self.corpus.citation(RNE_TABLE_DOC)
                cites = [c] if c else []
                text = "\n".join([i18n.t("code_not_found", lang, code=code)] + sources_footer(lang, cites))
                return ChecklistResult(text=text, found=False, citations=cites)
        top = req.passages[:RNE_TOP_PASSAGES]
        # Table rows in retrieval order (retrieval matches exact codes and company types); the
        # keyword heuristic is only a fallback when no table row was retrieved.
        if asked:
            # Exact identity takes precedence over vector similarity and company-name overlap. Several codes (one
            # legal form with several official rows) are quoted in the order given.
            rows = [row for c in asked_codes for row in table
                    if re.sub(r"\s+", "", row.splitlines()[0].split(":", 1)[-1]).upper() == "RNE" + c]
            top = []  # Do not append unrelated legal extracts to a code-specific answer.
        else:
            rows = self._retrieved_rows(top) or self._rank_rne_rows(req.query, req.passages)
        citations: list[Citation] = []
        lines: list[str] = []
        if route.intent in {"required_documents", "procedure_info"}:
            lines.append(i18n.t("no_checklist", lang))
        sections: list[ChecklistSection] = []
        # Other official texts ranked first by retrieval (e.g. the fee decree, the RNE law) are quoted
        # verbatim before the table rows.
        extracts = [p for p in top[:RNE_EXTRACTS] if p.citation.doc_id != RNE_TABLE_DOC
                    and p.citation.document_type != "official_form"]
        for p in extracts:
            body = _strip_heading_prefix(p.text)
            if lines:
                lines.append("")
            lines.append(f"📜 {body[:RNE_EXTRACT_CHARS].strip()}{'…' if len(body) > RNE_EXTRACT_CHARS else ''}")
            sections.append(ChecklistSection(kind="other", heading=p.citation.title, items=[body]))
            if p.citation.doc_id not in {c.doc_id for c in citations}:
                citations.append(p.citation)
        if rows:
            c = self.corpus.citation(RNE_TABLE_DOC)
            sections.append(ChecklistSection(kind="other", heading=c.title if c else RNE_TABLE_DOC, items=rows))
            if c:
                citations.append(c)
            for row in rows:
                if lines:
                    lines.append("")
                lines.extend(_localize_row(row, lang))
        forms = [r for r in self.corpus.records().values()
                 if r.procedure_category.value == "business_registration" and r.document_type.value == "official_form"]
        # Only the declaration form of the quoted rows' kind: F-001 natural person, F-002 legal entity.
        kinds = {("physique" if "Genre d'Entreprise: Personne physique" in row else "morale") for row in rows}
        if len(kinds) == 1:
            wanted_form = "rne-form-f001" if kinds == {"physique"} else "rne-form-f002"
            forms = [r for r in forms if r.doc_id.startswith(wanted_form)] or forms
        if forms:
            lines += ["", f"📝 {i18n.t('official_forms', lang)}:"]
            for f in sorted(forms, key=lambda r: r.doc_id):
                lines.append(f"• {f.title}\n  {f.url}")
                c = self.corpus.citation(f.doc_id)
                if c:
                    citations.append(c)
        if not rows and not forms and not extracts:
            return ChecklistResult(text=i18n.t("not_found", lang), found=False)
        if lang != "fr" and (rows or extracts):
            lines += ["", f"ℹ️ {i18n.t('original_language', lang, source='FR')}"]
        result = ChecklistResult(text="", found=bool(rows or extracts), doc_id=RNE_TABLE_DOC if rows else None,
                                 source_language="fr", sections=sections, citations=citations)
        header = f"{ICONS['business_registration']} {i18n.t('rne_header', lang)}"
        result.text = "\n".join([header, ""] + lines + sources_footer(lang, citations))
        return result

    def _retrieved_rows(self, passages: list[RetrievedPassage]) -> list[str]:
        """Official table rows contained in the retrieved table chunks, in retrieval order."""
        blocks = [b["text"] for b in self.corpus.blocks(RNE_TABLE_DOC) if b["kind"] == "table_row"]
        normalized = [(b, norm(b)) for b in blocks]
        rows: list[str] = []
        for p in passages:
            if p.citation.doc_id != RNE_TABLE_DOC:
                continue
            chunk = norm(p.text)
            for block, nb in normalized:
                if nb and nb in chunk and block not in rows:
                    rows.append(block)
            if len(rows) >= MAX_ROWS:
                break
        return rows[:MAX_ROWS]

    def _rank_rne_rows(self, query: str, passages: list[RetrievedPassage]) -> list[str]:
        """Rank rows of the official RNE formalities table against the question (deterministic)."""
        blocks = self.corpus.blocks(RNE_TABLE_DOC)
        rows = [b["text"] for b in blocks if b["kind"] == "table_row"]
        if not rows:
            return []
        q = norm(query)
        retrieved = " ".join(p.text for p in passages if p.citation.doc_id == RNE_TABLE_DOC)

        def score(row: str) -> float:
            r = norm(row)
            s = 0.0
            for pattern, needle in ENTITY_PATTERNS:
                if re.search(pattern, q):
                    s += 3 if needle in r else 0
            if re.search(CREATION_PATTERN, q) or not re.search(r"modif|radiation|تنقيح|تشطيب", q):
                s += 1 if "procédure: création" in r else 0
                s += 1 if "immatriculation principale" in r else 0
            code = re.search(r"rne [a-z] ?\d{3}", r)
            if code and code.group(0) in norm(retrieved):
                s += 0.5
            return s

        ranked = sorted(rows, key=score, reverse=True)
        best = score(ranked[0])
        return [r for r in ranked[:MAX_ROWS] if score(r) >= max(best - 1, 1)]

    def _passport_abroad_fee_details(self, route: RouteDecision, result: ChecklistResult) -> str | None:
        """Clarify applicant groups only when the selected source and aligned version agree."""
        if (route.procedure_category != "passport" or route.intent != "fees" or "abroad" not in route.hints
                or result.fee_discrepancy or not result.doc_id):
            return None
        items = [item for section in result.sections if section.kind == "fees" for item in section.items]
        reduced = [item for item in items if re.search(r"élèves|للتلاميذ", item) and re.search(r"étudiants|الطلبة", item)
                   and re.search(r"\b6\b", item)]
        standard = [item for item in items if re.search(r"autres|للبقية", item)]
        if len(reduced) != 1 or len(standard) != 1:
            return None
        a, b = list(AMOUNT.finditer(reduced[0])), list(AMOUNT.finditer(standard[0]))
        if len(a) != 1 or len(b) != 1:
            return None
        scenario = next((s for s in self.corpus.scenarios(result.doc_id) if s.title == result.scenario), None)
        parallel = self._parallel(result.doc_id, scenario) if scenario else None
        if parallel is None:
            return None
        # The foreign-currency qualification must actually occur in this scenario's Arabic text.
        evidence = items + [item for section in parallel[1].sections for item in section.items]
        if not any("بالعملة الأجنبية" in item for item in evidence):
            return None
        return i18n.t("passport_abroad_fee_categories", route.language,
                      reduced=a[0].group(1), standard=b[0].group(1))

    # ------------------------------------------------------------------ rendering
    def _render(self, route: RouteDecision, title: str, result: ChecklistResult) -> str:
        lang = route.language
        out = [f"{ICONS.get(route.procedure_category, '📋')} {title}"]
        for s in result.sections:
            items = s.translated_items or s.items
            out += ["", f"▪️ {i18n.t(s.kind, lang)}"]
            out += [f"• {i.strip()}" for i in items]
        details = self._passport_abroad_fee_details(route, result)
        if details:
            out += ["", details]
        out.append("")
        for w in result.warnings:
            out.append(f"⚠️ {w}")
        label = i18n.SOURCE_LANGUAGE_LABEL.get(result.source_language or "", "?")
        if result.translation and result.translation.get("validated"):
            key = "application_translation" if result.translation.get("method") == "explicit_cin_ar_v1" else "machine_translation"
            out.append("ℹ️ " + i18n.t(key, lang, source=label))
        elif result.source_language != TARGET_LANGUAGE[lang]:
            out.append("ℹ️ " + i18n.t("translation_unavailable", lang, source=label))
        elif lang == "derja" and result.source_language == "ar":
            # Derja explanations around the official Modern Standard Arabic text, which is never rewritten.
            out.append(f"ℹ️ {i18n.t('official_msa', lang)}")
        if result.alternatives and route.intent != "eligibility":
            out.append("")
            out.append(f"↪️ {i18n.t('other_cases', lang)}: " + " | ".join(a.rstrip(".") for a in result.alternatives[:6]))
        return "\n".join(out + sources_footer(lang, result.citations))


