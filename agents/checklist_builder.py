# Field names of the official RNE table rows. Only these labels are localised; the values (codes,
# services, fees, deadlines) are always quoted verbatim in French.
RNE_FIELDS = {
    "Code procédure": "rne_code", "Nature du service": "rne_service", "Genre d'Entreprise": "rne_kind",
    "Type d entreprise": "rne_type", "Procédure": "rne_procedure", "Redevance demandée": "rne_fee",
    "Délais": "rne_deadline",
}


def _localize_row(row: str, lang: str) -> list[str]:
    """Prefixes each official line with its label in the user's language; the official line itself
    (label and value) stays verbatim, so the quotation is preserved."""
    if lang == "fr":
        return row.splitlines()
    out = []
    for line in row.splitlines():
        key = RNE_FIELDS.get(line.partition(": ")[0])
        out.append(f"{i18n.t(key, lang)} — {line}" if key else line)
    return out


def _strip_heading_prefix(text: str) -> str:
    """Structure chunks start with their heading path ("Title > Section"); keep the official body."""
    first, _, rest = text.partition("\n")
    return rest.strip() if " > " in first and rest.strip() else text.strip()


def sources_footer(lang: str, citations: list[Citation], pages: dict[str, list[int]] | None = None) -> list[str]:
    out = ["", f"📚 {i18n.t('sources', lang)}:"]
    for n, c in enumerate(citations, 1):
        ref = f" — {c.official_reference}" if c.official_reference else ""
        doc_pages = (pages or {}).get(c.doc_id)
        where = f" — p. {', '.join(map(str, doc_pages))}" if doc_pages else ""
        out.append(f"[{n}] {c.title} ({c.source_organization}){ref}{where}\n{c.url}")
    out += ["", f"⚖️ {i18n.t('disclaimer', lang)}"]
    return out


def _parse_numbered(text: str, expected: int) -> list[str] | None:
    found: dict[int, str] = {}
    for line in text.splitlines():
        m = re.match(r"^\s*(\d+)[.)]\s*(.+)$", line)
        if m:
            found.setdefault(int(m.group(1)), m.group(2).strip())
    if sorted(found) != list(range(1, expected + 1)):
        return None
    return [found[n] for n in range(1, expected + 1)]


def _same_numbers(source: str, translated: str) -> bool:
    def nums(s: str) -> list[str]:
        s = s.replace("⁄", "/")  # the official ID guide writes "3⁄4 cm" with a fraction slash
        return sorted(n.replace(",", ".").lstrip("0") or "0" for n in NUMBER.findall(s))

    return nums(source) == nums(translated)

